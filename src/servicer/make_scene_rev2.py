def stl(path):
    """Binary STL -> (vertices, faces), duplicate vertices merged (as p6 rev1_scene._stl)."""
    b = path.read_bytes()
    n = struct.unpack_from("<I", b, 80)[0]
    rec = np.frombuffer(b, dtype=np.dtype([("n", "<f4", 3), ("v", "<f4", (3, 3)), ("a", "<u2")]), count=n, offset=84)
    v = rec["v"].reshape(-1, 3).astype(float)
    u, inv = np.unique(np.round(v, 7), axis=0, return_inverse=True)
    return u, inv.reshape(-1, 3)


def mujoco_quat_mul(res, a, b):
    """res = a * b (w x y z), as mujoco.mju_mulQuat (kept here: the builder does not import mujoco)."""
    w1, x1, y1, z1 = a
    w2, x2, y2, z2 = b
    res[:] = [w1 * w2 - x1 * x2 - y1 * y2 - z1 * z2, w1 * x2 + x1 * w2 + y1 * z2 - z1 * y2,
              w1 * y2 - x1 * z2 + y1 * w2 + z1 * x2, w1 * z2 + x1 * y2 - y1 * x2 + z1 * w2]


def fmt(a, prec=6):
    return " ".join(f"{x:.{prec}g}" if prec else str(int(x)) for x in np.asarray(a, float).ravel())


def rep(s, a, b):
    assert s.count(a) == 1, a[:80]
    return s.replace(a, b)


def bus_block(bus):
    I = np.array(bus["inertia_kgm2"])
    L = ['      <!-- servicer rev 2 bus (models/servicer_rev_2, SPEC_7 D7): mass from parts, generated by '
         'projects/p7_unprepared_client/servicer/make_scene_rev2.py -->',
         f'      <inertial pos="{fmt(bus["com_m"])}" mass="{bus["mass_kg"]:.6g}" '
         f'fullinertia="{fmt([I[0, 0], I[1, 1], I[2, 2], I[0, 1], I[0, 2], I[1, 2]])}"/>']
    for cb in bus["collision_boxes"]:
        name = "servicer_bus" if cb["name"] == "bus_col" else f'srv2_col_{cb["name"]}'
        L.append(f'      <geom name="{name}" class="bus_col" type="box" pos="{fmt(cb["pos"])}" size="{fmt(cb["size"])}" '
                 f'rgba="0.85 0.7 0.2 0"/>')
    for n in bus["nozzles"]:
        L.append(f'      <site name="{n["name"]}" pos="{fmt(n["pos_m"])}" zaxis="{fmt(n["force_dir"])}" size="0.008" '
                 f'rgba="1 0.3 0.1 0.6" group="4"/>')
    for w in bus["wheels"]:
        L.append(f'      <site name="rw_{w["name"][-1]}" pos="{fmt(w["pos_m"])}" zaxis="{fmt(w["axis"])}" size="0.01" '
                 f'rgba="0.2 0.6 1 0.6" group="4"/>')
    meshes = []
    for p in bus["parts"]:
        v, f = stl(SRV2 / "parts" / f'{p["name"]}.stl')
        meshes.append(f'    <mesh name="srv2_{p["name"]}" vertex="{fmt(v, 7)}" face="{fmt(f, 0)}"/>')
        L.append(f'      <geom name="srv2_{p["name"]}" class="vis" type="mesh" mesh="srv2_{p["name"]}" contype="0" '
                 f'conaffinity="0" mass="0" rgba="{fmt(p["rgba"])}"/>')
    return "\n".join(L) + "\n", meshes


def client_block():
    src = ET.parse(CLIENT / "client_p7.xml").getroot()
    meshes = []
    for m in src.iter("mesh"):
        v, f = stl(CLIENT / "parts" / m.get("file"))
        meshes.append(f'    <mesh name="{m.get("name")}" vertex="{fmt(v, 7)}" face="{fmt(f, 0)}"/>')
    body = src.find("worldbody").find("body")
    # 21 Nov (ring tool v2, curved jaws): the client's ring collision was 48 straight segments per wall / lip (a
    # 39.6 mm chord sags 0.7 mm, more than the hook tip's 0.5 mm gap); regenerated here with RING_N segments
    # (P7_RING_N, default 144: 12.8 mm chords, 0.07 mm sag), same radii and heights as client_p7.xml
    n_seg = int(os.environ.get("P7_RING_N", "144"))
    old = [g for g in body.findall("geom") if (g.get("name") or "").startswith(("ring_wall_", "ring_lip_"))]
    for g in old:
        body.remove(g)
    for nm, xc, hx, r, hr in (("ring_wall", 0.78, 0.03, 0.294, 0.011), ("ring_lip", 0.8025, 0.0075, 0.311, 0.006)):
        ht = np.pi * r / n_seg * 1.03
        for k in range(n_seg):
            th = 2 * np.pi * k / n_seg
            ET.SubElement(body, "geom", {"name": f"{nm}_{k}", "class": "client_col", "type": "box",
                                         "pos": fmt([xc, r * np.cos(th), r * np.sin(th)]), "size": fmt([hx, hr, ht]),
                                         "quat": fmt([np.cos(th / 2), np.sin(th / 2), 0, 0]), "group": "3",
                                         "rgba": "0.6 0.6 0.65 0.4"})
    txt = ET.tostring(body, encoding="unicode")
    return "    " + txt.strip() + "\n", meshes


