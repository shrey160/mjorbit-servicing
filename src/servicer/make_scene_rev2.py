    def arc(name, r0, r1, x0, x1, mass, n=3, seg=20.0, wedge=None):
        """Ring tool v2/v3 (21 Nov): a jaw face concentric with the ring as n boxes along the arc (seg mm each).
        wedge (deg): instead a 4 mm thick pad whose top face is the hook tip's wedge, x = LIP_BOT - (r - R_LIP) tan,
        over r0..r1 (x0, x1 unused)."""
        rm, out = 0.5 * (r0 + r1), []
        for k in range(n):
            th = (k - (n - 1) / 2) * seg / rm
            qx = np.array([np.cos(-th / 2), np.sin(-th / 2), 0.0, 0.0])
            if wedge is None:
                xc, rc, hs, q = 0.5 * (x0 + x1), rm, ((x1 - x0) / 2, seg / 2 * 1.02, (r1 - r0) / 2), qx
            else:
                a = np.radians(wedge)
                xp = LIP_BOT - (rm - R_LIP) * np.tan(a)                 # the slope at the pad's mid radius
                xc, rc = xp + 2.0 * np.cos(a), rm + 2.0 * np.sin(a)     # 2 mm inside along the face normal
                hs = (2.0, seg / 2 * 1.02, (r1 - r0) / 2 / np.cos(a))
                qy = np.array([np.cos(-a / 2), 0.0, np.sin(-a / 2), 0.0])   # local x -> (cos a, 0, sin a)
                q = np.zeros(4)
                mujoco_quat_mul(q, qx, qy)
            c = (xc, rc * np.sin(th), rc * np.cos(th) - RCm)
            nm = name if k == (n - 1) // 2 else f"{name}_{k}"
            out.append(f'<geom name="{nm}" class="tool" type="box" pos="{mm(*c)}" quat="{fmt(q)}" '
                       f'size="{mm(*hs)}" mass="{mass / n:.4f}" rgba="0.22 0.26 0.3 0"/>')
        return out
