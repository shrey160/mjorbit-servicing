def build(client="p7", base_xml=None):
    """Build servicer_rev2_scene.xml from a base scene XML (pre-built XML is committed under assets/servicer_rev2/)."""
    bus = json.loads((SRV2 / "servicer_rev2_bus.json").read_text())
    base_dir_env = os.environ.get("MJORBIT_BASE_SCENE_DIR", "").strip()
    if base_xml is not None:
        base_path = Path(base_xml)
    elif base_dir_env:
        base_path = Path(base_dir_env) / BASE
    else:
        raise FileNotFoundError(
            f"Pre-built scene exists at {OUT}. To rebuild from scratch, pass base_xml or set MJORBIT_BASE_SCENE_DIR."
        )
    s = base_path.read_text()
    head = ("<!--\n  GENERATED by src/servicer/make_scene_rev2.py (do not edit). Servicer rev 2\n"
            f"  (P7 D7) on base camera scene, client {client}. Base scene header follows.\n-->\n")
    # bus: explicit inertial from the parts, colliding box, nozzle / wheel sites, visual parts
    a = s.index('      <geom name="servicer_bus"')
    b = s.index("/>", a) + 3
    blk, m_bus = bus_block(bus)
    s = s[:a] + blk + s[b:]
    # shoulder redesign (21 Nov, user; FreeCAD assembly check): in the P4 base scene the yaw axis (j1, along bus z)
    # sat at the face and its drum was drawn 50 mm out, crossing the pitch drum: two motors in one space, the yaw
    # drum off its own axis, and the drums sank into the face / MLI / the 8 mm arm base plate (x 0.250-0.258).
    # Now: the yaw axis SHOULDER_X out (55 mm above the plate surface); on the bus a flange and a clevis (two lugs,
    # |z| 120-135 mm about the axis) carrying the yaw shaft; on the yaw body two coaxial drums (|z| 65-115 mm) and a
    # yoke (side plates beside the pitch drum, top / bottom plates to the drums); the pitch drum unchanged, 50 mm
