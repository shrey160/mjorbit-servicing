def put_tool(s):
    """Swap the two-jaw gripper for the ring tool (scene text s); returns (s, tool meshes)."""
    a = s.index('                  <geom name="palm" class="grip"')
    b = s.index('<body name="jaw_l"', a)
    b = s.index("</body>", b) + len("</body>\n")
    blk, meshes = tool_block()
    s = s[:a] + blk + s[b:]
    s = rep(s, '    <default class="client_col">',
            '    <default class="tool">\n      <geom contype="2" conaffinity="4" condim="4" friction="0.4 0.02 0.001"\n'
            '            solref="0.004 1" solimp="0.95 0.99 0.001"/>\n    </default>\n    <default class="client_col">')
    # non-backdrivable lead-screw drives: stiff position servos (holding force up to 150 N), slow
    for j in ("u", "l"):
        a = s.index(f'<position name="grip_{j}_pos"')
        b = s.index("/>", a)
        kp, fr = (30000, 300) if j == "u" else (10000, 150)   # the hook holds against the inboard push (21 Nov gate)
        s = s[:a] + f'<position name="grip_{j}_pos" joint="grip_{j}" kp="{kp}" kv="{kp // 25}" forcerange="-{fr} {fr}" ctrlrange="-0.03 0.03"' + s[b:]
    # open: hook 18 mm past contact along its path (tip 15 mm clear of the lip), inboard 20 mm off the wall;
    # squeeze target 4 mm past contact (40 N per drive)
    s = s.replace('<numeric name="grip_open" data="0.06 -0.06"/>', '<numeric name="grip_open" data="0.018 -0.012"/>')
    s = s.replace('<numeric name="grip_squeeze" data="0.03"/>', '<numeric name="grip_squeeze" data="0.012"/>')
    assert "<sensor>" not in s
    s = rep(s, "  </actuator>\n", "  </actuator>\n" + TOOL_SENSORS)
    return s, meshes


